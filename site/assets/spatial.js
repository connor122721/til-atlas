// Spatial tab: tissue map, neighborhood enrichment heatmap, response comparison, sample table.
// Data: data/spatial/index.json -> <path>{samples,nhood}.json + cells/<sample>.json (analysis/spatial/export_spatial.py).
(async function () {
  const { css, fmt, pct, esc } = TIL, { rankSumP, pTxt, strip } = TILStats;
  const $ = (s) => document.querySelector(s);
  const index = (await TIL.load("data/spatial/index.json")).data;
  const catalog = (await TIL.load("data/catalog.json")).data;
  if (!index || !index.datasets.length) {
    TIL.banner($("#main"), "No spatial data found.", "Run <code>analysis/spatial/export_spatial.py</code> (see analysis/spatial/README.md)."); return;
  }
  const RESP = { Responder: "--s1", "Non-responder": "--s2" };
  const slug = (s) => String(s).replace(/[^A-Za-z0-9_.-]+/g, "_");

  index.datasets.forEach((d) => $("#dataset").insertAdjacentHTML("beforeend", `<option value="${esc(d.id)}">${esc(d.label)}${d.synthetic ? " (synthetic)" : ""}</option>`));
  if (catalog) {
    const have = new Set(index.datasets.map((d) => d.id)), tag = { open: "good", check: "warning", unknown: "" };
    const q = catalog.datasets.filter((d) => d.use.includes("spatial") && !have.has(d.id));
    if (q.length) $("#queued").innerHTML = `<span class="muted">Not loaded yet:</span> ` + q.map((d) =>
      `<a href="datasets.html" class="pill ${tag[d.access]}" title="${esc(d.status)}">${esc(d.short)}</a>`).join(" ") +
      ` <span class="muted">— recipes in <code>analysis/spatial/README.md</code>.</span>`;
  }

  let D, cellsCache = {}, curCells = null;
  async function selectDataset(id) {
    const ds = index.datasets.find((d) => d.id === id);
    const [s, n] = await Promise.all([TIL.load(`${ds.path}samples.json`), TIL.load(`${ds.path}nhood.json`)]);
    D = { ds, meta: s.data.meta, samples: s.data.samples, types: n.data.types, z: n.data.z };
    cellsCache = {};
    $("#dsBanner").innerHTML = "";
    if (ds.synthetic) TIL.banner($("#dsBanner"), "Synthetic demo data.",
      "These tissue cores were generated by <code>analysis/spatial/make_synthetic_tissue.py</code>, with CD8⁺ cells deliberately placed near " +
      "myeloid hubs and inside tumor nests for “responders” and pushed into stroma for “non-responders”. They exercise the real pipeline; they are not measurements.");
    $("#dsNote").textContent = [D.meta.platform, D.meta.study, D.meta.therapy, `${D.samples.length} samples`].filter(Boolean).join(" · ");
    $("#sample").innerHTML = D.samples.map((s) => `<option value="${esc(s.sample)}">${esc(s.sample)}${s.response ? " · " + s.response : ""}</option>`).join("");
    const opts = (sel) => D.types.map((t) => `<option${t === sel ? " selected" : ""}>${esc(t)}</option>`).join("");
    const other = D.types.includes("Myeloid") ? "Myeloid" : D.types.find((t) => t !== D.meta.focal);
    $("#focal").innerHTML = opts(D.meta.focal); $("#target").innerHTML = opts(D.meta.target);
    $("#pairA").innerHTML = opts(D.meta.focal); $("#pairB").innerHTML = opts(other);
    const hasR = D.samples.some((s) => s.response);
    ["R", "NR", "diff"].forEach((v) => ($(`#hmMode option[value=${v}]`).disabled = !hasR));
    if (!hasR) $("#hmMode").value = "sample";
    $("#metric").innerHTML = [["pair", "Contact z-score for a cell-type pair"], ["density", `${D.meta.focal} density (cells/mm²)`],
      ["dist", `Median ${D.meta.focal} → ${D.meta.target} distance (µm)`], ["within20", `${D.meta.focal} within 20 µm of ${D.meta.target}`]]
      .map(([v, l]) => `<option value="${v}">${esc(l)}</option>`).join("");
    $("#hmSub").textContent = `Contact radius ${D.meta.radiusUm} µm, ${D.meta.perms} label permutations`;
    drawTable(); await selectSample(D.samples[0].sample); drawHeat(); drawStrip();
  }
  async function selectSample(sid) {
    $("#sample").value = sid;
    if (!cellsCache[sid]) cellsCache[sid] = (await TIL.load(`${D.ds.path}cells/${slug(sid)}.json`)).data;
    curCells = cellsCache[sid];
    drawMap(); if ($("#hmMode").value === "sample") drawHeat();
    document.querySelectorAll("#sampleTable tbody tr").forEach((tr) => tr.classList.toggle("sel", tr.dataset.s === sid));
  }

  // ---------------- tissue map (canvas, equal aspect, scale bar)
  function drawMap() {
    const c = curCells, el = $("#map2d"); el.innerHTML = "";
    if (!c) { el.innerHTML = `<p class="muted small">Cells for this sample weren't exported.</p>`; return; }
    const s = D.samples.find((x) => x.sample === c.sample);
    $("#mapSub").textContent = `${s.sample}${s.response ? " · " + s.response : ""} · ${fmt(c.nTotal)} cells${c.x.length < c.nTotal ? ` (${fmt(c.x.length)} drawn)` : ""} · ${s.areaMm2} mm²`;
    const W = el.clientWidth, H = el.clientHeight || W / 1.25, dpr = devicePixelRatio || 1, pad = 14;
    const cv = Object.assign(document.createElement("canvas"), { width: W * dpr, height: H * dpr });
    cv.style.width = W + "px"; cv.style.height = H + "px"; cv.setAttribute("role", "img"); cv.setAttribute("aria-label", "Map of cells in the tissue section");
    el.append(cv);
    const ctx = cv.getContext("2d"); ctx.scale(dpr, dpr);
    const xmax = d3.max(c.x), ymax = d3.max(c.y), k = Math.min((W - 2 * pad) / xmax, (H - 2 * pad - 18) / ymax);
    const ox = (W - xmax * k) / 2, oy = pad;
    const px = (i) => ox + c.x[i] * k, py = (i) => oy + c.y[i] * k;
    const fi = D.types.indexOf($("#focal").value), ti = D.types.indexOf($("#target").value);
    const r = Math.max(1.2, Math.min(3.2, 2600 / Math.sqrt(c.x.length) / 40 * (W / 600)));
    const layer = (pred, color, rr) => { ctx.fillStyle = color; ctx.beginPath();
      for (let i = 0; i < c.x.length; i++) if (pred(c.t[i])) { ctx.moveTo(px(i) + rr, py(i)); ctx.arc(px(i), py(i), rr, 0, 6.283); } ctx.fill(); };
    layer((t) => t !== fi && t !== ti, css("--axis"), r * 0.8);
    layer((t) => t === ti, css("--s2"), r);
    layer((t) => t === fi, css("--s1"), r * 1.15);
    // scale bar: largest of 50/100/200/500 µm that fits in a quarter of the width
    const bar = [500, 200, 100, 50].find((b) => b * k < W / 4) || 50;
    ctx.fillStyle = css("--text-primary"); ctx.fillRect(W - pad - bar * k, H - 12, bar * k, 3);
    ctx.font = `11.5px ${getComputedStyle(document.body).fontFamily}`; ctx.textAlign = "right"; ctx.fillStyle = css("--text-secondary");
    ctx.fillText(`${bar} µm`, W - pad, H - 17);
    const n = (t) => c.t.filter((u) => u === t).length;
    $("#mapLegend").innerHTML = `<span><i style="background:${css("--s1")}"></i>${esc(D.types[fi])} · ${fmt(n(fi))}</span>` +
      (ti !== fi ? `<span><i style="background:${css("--s2")}"></i>${esc(D.types[ti])} · ${fmt(n(ti))}</span>` : "") +
      `<span><i style="background:${css("--axis")}"></i>all other cells</span>`;
    const qt = d3.quadtree().x(px).y(py).addAll(d3.range(c.x.length));
    cv.addEventListener("mousemove", (ev) => {
      const b = cv.getBoundingClientRect(), i = qt.find(ev.clientX - b.left, ev.clientY - b.top, 8);
      if (i == null) return TIL.hideTip();
      TIL.showTip(`<div class="tt-title">${esc(D.types[c.t[i]])}</div><div class="row">x, y<b>${c.x[i].toFixed(0)}, ${c.y[i].toFixed(0)} µm</b></div>`, ev);
    });
    cv.addEventListener("mouseleave", TIL.hideTip);
  }

  // ---------------- heatmap of z-scores
  function matrixFor(mode) {
    const k = D.types.length, sid = $("#sample").value;
    if (mode === "sample") return D.z[sid];
    const mean = (resp) => { const ss = D.samples.filter((s) => s.response === resp && D.z[s.sample]);
      return d3.range(k).map((i) => d3.range(k).map((j) => d3.mean(ss, (s) => D.z[s.sample][i][j]))); };
    if (mode === "R") return mean("Responder");
    if (mode === "NR") return mean("Non-responder");
    const a = mean("Responder"), b = mean("Non-responder");
    return a.map((row, i) => row.map((v, j) => (v == null || b[i][j] == null ? null : v - b[i][j])));
  }
  function drawHeat() {
    const el = $("#heat"); el.innerHTML = "";
    const mode = $("#hmMode").value, M = matrixFor(mode), T = D.types, k = T.length;
    const W = el.clientWidth || 340, lab = Math.min(96, W * 0.3), top = 72, cell = Math.max(10, (W - lab - 4) / k), H = top + cell * k;
    const vmax = Math.max(2, d3.quantile(M.flat().filter((v) => v != null).map(Math.abs).sort(d3.ascending), 0.95) || 2);
    const col = d3.scaleLinear().domain([-vmax, -vmax / 2, 0, vmax / 2, vmax])
      .range(["--div-n2", "--div-n1", "--div-0", "--div-p1", "--div-p2"].map(css)).clamp(true);
    const svg = d3.select(el).append("svg").attr("viewBox", `0 0 ${W} ${H}`).attr("role", "img").attr("aria-label", "Neighborhood enrichment matrix");
    T.forEach((t, i) => {
      svg.append("text").attr("x", lab - 6).attr("y", top + i * cell + cell / 2).attr("dy", "0.35em").attr("text-anchor", "end")
        .attr("font-size", 11).attr("fill", css("--text-secondary")).text(t);
      svg.append("text").attr("transform", `translate(${lab + i * cell + cell / 2},${top - 6}) rotate(-50)`).attr("font-size", 11)
        .attr("fill", css("--text-secondary")).text(t);
    });
    const desc = { sample: `sample ${$("#sample").value}`, R: "responders (mean)", NR: "non-responders (mean)", diff: "responders − non-responders" }[mode];
    svg.append("g").selectAll("rect").data(d3.cross(d3.range(k), d3.range(k))).join("rect")
      .attr("x", ([, j]) => lab + j * cell + 1).attr("y", ([i]) => top + i * cell + 1).attr("width", cell - 2).attr("height", cell - 2).attr("rx", 2)
      .attr("fill", ([i, j]) => (M[i][j] == null ? css("--surface-2") : col(M[i][j])))
      .on("mousemove", (ev, [i, j]) => TIL.showTip(`<div class="tt-title">${esc(T[i])} ↔ ${esc(T[j])}</div>
        <div class="row">${mode === "diff" ? "Δ z" : "z"}, ${esc(desc)}<b>${M[i][j] == null ? "n/a" : M[i][j].toFixed(1)}</b></div>
        <div class="small muted">${M[i][j] == null ? "" : M[i][j] > 0 ? "found together more than chance" : "found together less than chance"}</div>`, ev))
      .on("mouseleave", TIL.hideTip)
      .on("click", (ev, [i, j]) => { $("#pairA").value = T[i]; $("#pairB").value = T[j]; $("#metric").value = "pair"; drawStrip(); });
    const stops = [-vmax, -vmax / 2, 0, vmax / 2, vmax].map((v) => col(v)).join(",");
    $("#hmLegend").innerHTML = `<span>${(-vmax).toFixed(0)}</span><span style="width:120px;height:8px;border-radius:4px;background:linear-gradient(90deg,${stops})"></span><span>+${vmax.toFixed(0)} ${mode === "diff" ? "Δz" : "z"}</span><span class="muted">· click a cell to compare it by response</span>`;
  }

  // ---------------- response comparison
  function metricFn() {
    const m = $("#metric").value, i = D.types.indexOf($("#pairA").value), j = D.types.indexOf($("#pairB").value), f = D.meta.focal;
    $("#pairPick").hidden = m !== "pair";
    if (m === "pair") return { v: (s) => D.z[s.sample]?.[i]?.[j] ?? null, fmtY: d3.format(".0f"), name: `z, ${D.types[i]} ↔ ${D.types[j]}`, zero: true };
    if (m === "density") return { v: (s) => s.density[f], fmtY: d3.format("~s"), name: `${f} per mm²` };
    if (m === "dist") return { v: (s) => s.focalToTarget?.median ?? null, fmtY: d3.format(".0f"), name: "median distance, µm" };
    return { v: (s) => s.focalToTarget?.within20 ?? null, fmtY: d3.format(".0%"), name: `share of ${f} within 20 µm` };
  }
  function drawStrip() {
    const M = metricFn(), hasR = D.samples.some((s) => s.response);
    const groups = hasR ? Object.keys(RESP).map((r) => ({ key: r, label: r, color: RESP[r], rows: D.samples.filter((s) => s.response === r) }))
      : [{ key: "all", label: "All samples", color: "--s1", rows: D.samples }];
    strip($("#strip"), groups, M.v, { fmtY: M.fmtY, zeroLine: M.zero,
      tip: (s) => `<div class="tt-title">${esc(s.sample)}${s.response ? " · " + s.response : ""}</div><div class="row">${esc(M.name)}<b>${M.v(s) == null ? "n/a" : M.fmtY(M.v(s))}</b></div>` });
    if (!hasR) { $("#stats").textContent = "This dataset has no treatment response, so samples are shown together."; return; }
    const a = groups[0].rows.map(M.v).filter((v) => v != null), b = groups[1].rows.map(M.v).filter((v) => v != null);
    $("#stats").innerHTML = `${esc(M.name)}: two-sided Wilcoxon rank-sum, ${a.length} vs ${b.length} samples, <b>p = ${pTxt(rankSumP(a, b))}</b>.`;
  }

  // ---------------- sample table
  function drawTable() {
    const f = D.meta.focal, t = D.meta.target;
    $("#sampleTable thead").innerHTML = `<tr><th>Sample</th><th>Patient</th><th>Response</th><th class="num">Cells</th><th class="num">mm²</th>
      <th class="num">${esc(f)} /mm²</th><th class="num">${esc(f)}→${esc(t)} median µm</th></tr>`;
    $("#sampleTable tbody").innerHTML = D.samples.map((s) => `<tr data-s="${esc(s.sample)}" tabindex="0" style="cursor:pointer">
      <td class="mono">${esc(s.sample)}</td><td>${esc(s.patient ?? "")}</td><td>${s.response ? `<span class="pill ${s.response === "Responder" ? "good" : "critical"}">${esc(s.response)}</span>` : "—"}</td>
      <td class="num">${fmt(s.nCells)}</td><td class="num">${s.areaMm2}</td><td class="num">${fmt(s.density[f])}</td>
      <td class="num">${s.focalToTarget ? fmt(s.focalToTarget.median) : "—"}</td></tr>`).join("");
  }
  $("#sampleTable tbody").addEventListener("click", (e) => { const tr = e.target.closest("tr[data-s]"); if (tr) selectSample(tr.dataset.s); });
  $("#sampleTable tbody").addEventListener("keydown", (e) => { const tr = e.target.closest("tr[data-s]"); if (tr && e.key === "Enter") selectSample(tr.dataset.s); });

  $("#dataset").addEventListener("change", (e) => selectDataset(e.target.value));
  $("#sample").addEventListener("change", (e) => selectSample(e.target.value));
  ["#focal", "#target"].forEach((s) => $(s).addEventListener("change", drawMap));
  $("#hmMode").addEventListener("change", drawHeat);
  ["#metric", "#pairA", "#pairB"].forEach((s) => $(s).addEventListener("change", drawStrip));
  const all = () => { if (D) { drawMap(); drawHeat(); drawStrip(); } };
  let rt; window.addEventListener("resize", () => { clearTimeout(rt); rt = setTimeout(all, 150); });
  window.addEventListener("themechange", all);
  const first = index.datasets.find((d) => !d.synthetic) || index.datasets[0];
  $("#dataset").value = first.id;
  selectDataset(first.id);
})();
